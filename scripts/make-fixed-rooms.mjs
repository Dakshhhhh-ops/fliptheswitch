#!/usr/bin/env node
// Writes template/crypto-desk-fixed-rooms.template.yaml, the backup version
// of the desk template: the template itself creates the three work rooms
// (F5, F1, F3) instead of the scout creating them at run time. Use it if a
// run keeps failing while the scout opens rooms. Everything else, the
// agents, their instructions and the ship gate, is the same, because the
// file is generated from the main template:
//
//   node scripts/make-fixed-rooms.mjs
//
// test/templates.test.mjs fails if the committed file is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'template');
export const MAIN = join(DIR, 'crypto-desk.template.yaml');
export const FIXED = join(DIR, 'crypto-desk-fixed-rooms.template.yaml');

export const ROOMS = [
  { key: 'f5', id: 'F5', stem: 'webhooks', problem: 'ECDSA P-256 webhook signatures' },
  { key: 'f1', id: 'F1', stem: 'envelope', problem: 'RSA-OAEP wraps card data keys' },
  { key: 'f3', id: 'F3', stem: 'tls', problem: 'classical-only TLS key exchange' },
];

function replaceOnce(text, from, to) {
  const at = text.indexOf(from);
  if (at < 0 || text.indexOf(from, at + 1) >= 0) throw new Error(`make-fixed-rooms: expected exactly one "${from.trim().slice(0, 60)}" in the main template`);
  return text.slice(0, at) + to + text.slice(at + from.length);
}

export function build(main) {
  const ids = ROOMS.map((r) => r.id).join(', ');
  const names = ROOMS.map((r) => `{team}-${r.key}-${r.stem}`);
  let t = main;

  t = replaceOnce(t, '# Crypto Migration Desk\n', `# Crypto Migration Desk (fixed rooms)
#
# GENERATED by scripts/make-fixed-rooms.mjs from crypto-desk.template.yaml.
# Don't edit it by hand. The backup version: this template creates the work
# rooms for ${ids} itself, so the scout doesn't open rooms at run time.
#
`);

  // The focus is fixed: these are the rooms that exist.
  t = t.replace(/(  focus:\n(?:    .*\n)*?    default: ).*\n/, `$1${ids}\n    input: advanced\n`);
  t = replaceOnce(t, '    label: Findings to work\n', `    label: 'Findings to work (fixed: the template creates rooms for ${ids})'\n`);

  // The scout fills the rooms the template made instead of creating them.
  const start = t.indexOf('      ## Opening work rooms\n');
  const brief = t.indexOf('      The finding brief has:', start);
  const end = t.indexOf('      ## Starting work\n', start);
  if (start < 0 || brief < 0 || end < 0) throw new Error('make-fixed-rooms: the scout\'s "Opening work rooms" section moved');
  t = `${t.slice(0, start)}      ## The work rooms
      This template already created the work rooms, linked from the intake
      room: ${names.join(', ')}. Don't create rooms. After the first scan,
      for each of them: \`connect_to_room\`, check the scan has that finding
      with that file (if not, say so in the intake room and stop), and
      \`create_room_document\` named "Finding brief" with the brief below.
      Then \`connect_to_room\` back to the intake room.

${t.slice(brief, end)}${t.slice(end)}`;

  t = replaceOnce(t, "The room's\n      instructions hold the finding brief.", 'The room\'s\n      "Finding brief" document holds the finding brief.');
  t = replaceOnce(
    t,
    'and open a work room\n      for each of {focus}. Work them in that order.',
    'and write the finding\n      brief in each work room. Work {focus}, in that order.',
  );
  t = replaceOnce(t, '  intake:\n    type: room\n', '  intake:\n    type: room\n    group: desk\n');

  const links = ROOMS.flatMap((r) => [
    `    - {from: intake, to: ${r.key}, label: finding ${r.id}}`,
    `    - {from: ${r.key}, to: intake, label: parent}`,
  ]);
  const rooms = ROOMS.map(
    (r) => `  ${r.key}:
    type: room
    group: desk
    name: '{team}-${r.key}-${r.stem}'
    description: '${r.id}: ${r.problem}'
    bridge: '{bridge}'
    channel_type: channel_private
    agents:
    - scout
    - migrator
    - reviewer
    - shipper
    users:
    - '{$creator}'
    - '{engineer}'
    roles:
    - name: reviewer
      exclusive: true
      instructions: You are the reviewer of record for this finding. Only your APPROVED verdict counts for shipping.
    instructions: |
      Work room for finding ${r.id} in {target_name}: ${r.problem}. {team}-scout
      writes the "Finding brief" document here after its first scan. Branch:
      pqc/${r.key}-${r.stem}. Rules: see the PQC rules in your own
      instructions. The security lead decides what ships; tell
      {team}-shipper nothing yourself.
`,
  );
  return `${t.trimEnd()}\n  desk:\n    type: group\n    name: '{team} desk'\n    description: Crypto migration desk for {target_name}\n    links:\n${links.join('\n')}\n${rooms.join('')}`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(FIXED, build(readFileSync(MAIN, 'utf8')));
  console.log(`Wrote ${FIXED}`);
}
